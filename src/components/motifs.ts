export type Motif = keyof typeof raw;

export function cells(name: Motif): Array<[number, number]> {
  const rows = raw[name].trim().split('\n');
  const out: Array<[number, number]> = [];
  rows.forEach((row, y) => [...row].forEach((ch, x) => ch === 'X' && out.push([x, y])));
  return out;
}

export function width(name: Motif): number {
  return raw[name].trim().split('\n')[0].length;
}
